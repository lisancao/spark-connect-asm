// Generate src/hpack_tables.s from RFC 7541 appendices A and B (same parse as the wasm project).
import { readFileSync, writeFileSync } from "node:fs";
const rfc = readFileSync(process.argv[2], "utf8");
const huff = [];
for (const m of rfc.matchAll(/^.{0,8}\(\s*(\d+)\)\s+\|[01|]+\s+([0-9a-f]+)\s+\[\s*(\d+)\]/gm)) huff[+m[1]] = [parseInt(m[2], 16), +m[3]];
if (huff.length !== 257 || huff.some((x) => !x)) throw new Error("huffman parse");
const stat = [];
for (const m of rfc.matchAll(/^\s+\|\s(\d+)\s+\|\s(\S+)\s+\|\s([^|]*?)\s*\|$/gm)) stat[+m[1]] = [m[2], m[3]];
if (stat.length !== 62 || stat.slice(1).some((x) => !x)) throw new Error("static parse");
let out = "# Generated by scripts/gen-hpack-tables.mjs from RFC 7541. Do not edit.\n\t.section .rodata\n\t.globl huff_table, static_idx, static_str\n\t.balign 8\nhuff_table:\n";
for (const [c, l] of huff) out += `\t.long 0x${c.toString(16)}, ${l}\n`;
let off = 0; const strs = []; out += "\t.balign 2\nstatic_idx:\n";
for (let i = 1; i <= 61; i++) { const [n, v] = stat[i]; out += `\t.short ${off}, ${n.length}, ${off + n.length}, ${v.length}\n`; strs.push(n, v); off += n.length + v.length; }
out += "static_str:\n\t.ascii " + JSON.stringify(strs.join("")) + "\n";
writeFileSync("src/hpack_tables.s", out); console.log("src/hpack_tables.s written");
